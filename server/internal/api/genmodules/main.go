// Command genmodules writes the open-source build's handlers for the
// operations of the paid modules (v1.13): every operation the spec marks
// with `x-kept-module` answers “not in this build”. The official build
// (-tags ee) has the real handlers in internal/api/ee_*.go instead.
//
//	go run ./internal/api/genmodules ../api/openapi.yaml internal/api/oss_modules_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genmodules <openapi.yaml> <out.go>")
		os.Exit(2)
	}
	spec, err := openapi3.NewLoader().LoadFromFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	byModule := map[string][]string{}
	for _, item := range spec.Paths.Map() {
		for _, op := range item.Operations() {
			m, err := module(op.Extensions["x-kept-module"])
			if err != nil {
				fail(fmt.Errorf("%s: %w", op.OperationID, err))
			}
			if m != "" {
				byModule[m] = append(byModule[m], op.OperationID)
			}
		}
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by genmodules from api/openapi.yaml; DO NOT EDIT.

//go:build !ee

package api

import (
	"context"

	"kept/server/internal/api/gen"
)

// The open-source build has no paid modules: their operations answer
// errNotInBuild (v1.13). Grouped by the spec's x-kept-module.
`)
	modules := make([]string, 0, len(byModule))
	for m := range byModule {
		modules = append(modules, m)
	}
	sort.Strings(modules)
	for _, m := range modules {
		ops := byModule[m]
		sort.Strings(ops)
		fmt.Fprintf(&b, "\n// ---- %s ----\n", m)
		for _, id := range ops {
			name := strings.ToUpper(id[:1]) + id[1:]
			fmt.Fprintf(&b, "\nfunc (s *Server) %s(context.Context, gen.%sRequestObject) (gen.%sResponseObject, error) {\n\treturn nil, errNotInBuild\n}\n", name, name, name)
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], out, 0o644); err != nil {
		fail(err)
	}
}

func module(ext any) (string, error) {
	switch v := ext.(type) {
	case nil:
		return "", nil
	case string:
		return v, nil
	case json.RawMessage:
		var s string
		err := json.Unmarshal(v, &s)
		return s, err
	}
	return "", fmt.Errorf("x-kept-module: want a string, got %T", ext)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genmodules:", err)
	os.Exit(1)
}
